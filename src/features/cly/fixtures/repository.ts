const clone = <T>(value: T): T => structuredClone(value);

const makeLargeGraph = (): { nodes: GraphNode[]; edges: GraphEdge[] } => {
  const nodes: GraphNode[] = Array.from({ length: 2000 }, (_, index) => ({
    id: `large-node-${index}`,
    type: (
      ["source", "claim", "experiment", "run", "figure", "notebook"] as const
    )[index % 6],
    label: `${["Source", "Claim", "Experiment", "Run", "Figure", "Notebook"][index % 6]} ${index + 1}`,
    status:
      index % 17 === 0 ? "Suggested" : index % 29 === 0 ? "Stale" : "Confirmed",
    x: 40 + (index % 10) * 105,
    y: 30 + (Math.floor(index / 10) % 6) * 84,
  }));
  const edges: GraphEdge[] = Array.from({ length: 5000 }, (_, index) => ({
    id: `large-edge-${index}`,
    source: `large-node-${index % 2000}`,
    target: `large-node-${(index * 17 + 41) % 2000}`,
    relation: (
      ["supports", "produces", "uses", "depends on", "inferred"] as const
    )[index % 5],
    confidence: 0.55 + (index % 45) / 100,
    approved: index % 7 !== 0,
  }));
  return { nodes, edges };
};

