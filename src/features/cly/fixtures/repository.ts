export const createFixtureRepository = (
  mode: FixtureMode,
): ClyRepositoryData => {
  const data = clone(coreData);

  if (mode === "empty") {
    return {
      ...data,
      sources: [],
      claims: [],
      experiments: [],
      runs: [],
      notebooks: [],
      code: [],
      artifacts: [],
      findings: [],
      audits: [],
      nextSteps: [],
      decisions: [],
      contextItems: [],
      graphNodes: [],
      graphEdges: [],
      reports: [],
      agentSessions: [],
      activity: [],
    };
  }

  if (mode === "new") {
    return {
      ...data,
      sources: data.sources.slice(0, 1),
      claims: [],
      experiments: [],
      runs: [],
      notebooks: [],
      code: [],
      artifacts: [],
      findings: [],
      audits: [],
      nextSteps: data.nextSteps.slice(0, 1),
      decisions: [],
      contextItems: data.contextItems.slice(0, 1),
      graphNodes: data.graphNodes.slice(0, 2),
      graphEdges: data.graphEdges.slice(0, 1),
      reports: [],
      agentSessions: [],
      activity: data.activity.slice(0, 1),
    };
  }

  if (mode === "large") return withLargeData(data);

  if (mode === "risks") {
    data.claims = data.claims.map((claim, index) => ({
      ...claim,
      status: index % 2 ? "Weak" : "Needs review",
      confidence: Math.min(claim.confidence, 55),
    }));
    data.findings = data.findings.map((finding) =>
      finding.severity === "Passed"
        ? {
            ...finding,
            severity: "Warning",
            status: "Open",
            detail: "This check has become stale and must be rerun.",
          }
        : finding,
    );
    data.audits[0] = {
      ...data.audits[0],
      score: 43,
      status: "Partially reproducible",
    };
  }

  if (mode === "offline") {
    data.projects[0].localOnly = true;
    data.integrations = data.integrations.map((integration) => ({
      ...integration,
      status:
        integration.name === "Git" || integration.name === "Local folders"
          ? "Connected"
          : "Unavailable",
      lastSync: undefined,
    }));
  }

  if (mode === "errors") {
    data.integrations = data.integrations.map((integration, index) => ({
      ...integration,
      status:
        index % 3 === 0
          ? "Sync error"
          : index % 3 === 1
            ? "Permission required"
            : integration.status,
    }));
    data.activity.unshift({
      id: "activity-error",
      time: "Now",
      type: "system",
      title: "Test fixture service error",
      detail:
        "The selected state simulates partial data and integration failures.",
      status: "warning",
    });
    const session = data.agentSessions[0];
    const failedAgent = session?.delegatedAgents[0];
    if (session && failedAgent) {
      failedAgent.status = "failed";
      failedAgent.lastAction = "Process exited before returning a result";
      failedAgent.currentResource = "Test fixture runtime log · exit code 1";
      failedAgent.transcript.push(
        "The partial implementation result remains available for reassignment.",
      );
      session.risk =
        "High · Worker Agent failed; partial output can be retried or reassigned";
      session.messages.push({
        id: "message-agent-failure",
        type: "error",
        author: failedAgent.name,
        title: "Delegated Agent failed",
        body: "The process exited before handoff. Inspect logs, retry, or reassign the task; completed evidence remains attached.",
        timestamp: "Just now",
        agentId: failedAgent.id,
        actions: ["Inspect logs", "Retry", "Reassign"],
      });
    }
  }

  return data;
};
